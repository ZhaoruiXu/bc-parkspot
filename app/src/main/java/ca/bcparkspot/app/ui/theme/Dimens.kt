package ca.bcparkspot.app.ui.theme

import androidx.compose.ui.unit.dp

/** Spacing scale; every gap and padding comes from here. */
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
}

object Sizes {
    /** Material's minimum touch target; every tappable control is at least this big (3.2). */
    val minTouchTarget = 48.dp
    /** Gap kept between neighbouring icon buttons so a slightly-off tap cannot land on the wrong one. */
    val iconButtonGap = 8.dp
    val inlineIcon = 16.dp
    val statusIcon = 24.dp
    val statusDot = 10.dp
    val badgeCorner = 8.dp
    val brandMark = 32.dp
    val emptyStateIcon = 64.dp
    val brandMarkCorner = 8.dp
    val sheetCorner = 16.dp
    val messageCorner = 12.dp
    val progressStroke = 3.dp
    val progressIndicator = 24.dp
}
